-- PostgreSQL 18. Схема по ER-диаграмме; Flyway V1 для НОВОЙ базы.
CREATE TABLE role (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_role varchar(50) NOT NULL UNIQUE
);

CREATE TABLE department (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE
);

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login varchar(100) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    name varchar(100) NOT NULL,
    last_name varchar(100) NOT NULL,
    patronymic varchar(100),
    role_id smallint NOT NULL REFERENCES role(id),
    department_id bigint REFERENCES department(id)
);

CREATE INDEX idx_users_department ON users(department_id);
CREATE INDEX idx_users_role ON users(role_id);

CREATE TABLE audience (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number varchar(20) NOT NULL UNIQUE
);

CREATE TABLE service_catalog (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_service varchar(255) NOT NULL UNIQUE,
    description text,
    deadline integer NOT NULL CHECK (deadline > 0)
);

-- status_id на схеме требует справочник статусов; добавлен request_status.
CREATE TABLE request_status (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE
);

CREATE TABLE request (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    audience_id bigint NOT NULL REFERENCES audience(id),
    service_id bigint NOT NULL REFERENCES service_catalog(id),
    status_id smallint NOT NULL REFERENCES request_status(id),
    description text,
    approver_id bigint REFERENCES users(id),
    executor_id bigint REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    is_approved boolean,
    reject_reason text,
    CONSTRAINT chk_request_rejection CHECK (
        is_approved IS DISTINCT FROM false
        OR NULLIF(btrim(reject_reason), '') IS NOT NULL
    )
);

CREATE INDEX idx_request_user ON request(user_id);
CREATE INDEX idx_request_executor ON request(executor_id);
CREATE INDEX idx_request_status ON request(status_id);
CREATE INDEX idx_request_created_at ON request(created_at);

